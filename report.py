# ── Ranking Summary Table ─────────────────────────────────────────────────────
def build_ranking_table(story, styles, final_results):
    story.append(section_block("📊  CANDIDATE RANKING SUMMARY", styles))
    story.append(Spacer(1, 4*mm))

    headers = ["Rank", "Candidate", "Email", "Similarity", "Prediction", "Final Score", "Status"]
    col_widths = [12*mm, 32*mm, 45*mm, 20*mm, 22*mm, 22*mm, 22*mm]

    header_row = [Paragraph(h, styles["table_header"]) for h in headers]
    rows = [header_row]

    for rank, r in enumerate(final_results, 1):
        p     = r["parsed"]
        score = r["final_score"]
        sim   = round(r["similarity_score"] * 100, 1)
        pred  = round(r["prediction_prob"]  * 100, 1)
        status_lbl, status_col, _ = get_status_info(score)
        bg, fg = status_color_bg(score)

        status_para = Paragraph(
            f"<font color='#{status_col.hexval()[2:]}'><b>{status_lbl}</b></font>",
            styles["table_cell"])

        rows.append([
            Paragraph(f"<b>#{rank}</b>", styles["table_cell"]),
            Paragraph(p.get("Name", "—"), styles["table_cell"]),
            Paragraph(p.get("Email", "—"), ParagraphStyle(
                "em", fontName="Helvetica", fontSize=7.5,
                textColor=TEXT_DARK, alignment=TA_CENTER, leading=10)),
            Paragraph(f"{sim}%", styles["table_cell"]),
            Paragraph(f"{pred}%", styles["table_cell"]),
            Paragraph(f"<b>{score}%</b>", styles["table_cell"]),
            status_para,
        ])

    t = Table(rows, colWidths=col_widths, repeatRows=1)
    ts = TableStyle([
        # Header
        ("BACKGROUND",    (0,0), (-1,0), SLATE),
        ("TEXTCOLOR",     (0,0), (-1,0), WHITE),
        ("FONTNAME",      (0,0), (-1,0), "Helvetica-Bold"),
        ("FONTSIZE",      (0,0), (-1,0), 8.5),
        ("ROWPADDING",    (0,0), (-1,-1), 6),
        ("GRID",          (0,0), (-1,-1), 0.5, colors.HexColor("#e5e7eb")),
        ("VALIGN",        (0,0), (-1,-1), "MIDDLE"),
        ("ALIGN",         (0,0), (-1,-1), "CENTER"),
        ("ROWBACKGROUNDS",(0,1), (-1,-1), [WHITE, LIGHT_GRAY]),
        ("LINEBELOW",     (0,0), (-1,0), 2, PURPLE),
    ])

    # Color status column per row
    for i, r in enumerate(final_results, 1):
        score = r["final_score"]
        bg, fg = status_color_bg(score)
        ts.add("BACKGROUND", (6, i), (6, i), bg)

    t.setStyle(ts)
    story.append(t)
    story.append(Spacer(1, 6*mm))


