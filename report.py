# ── Inline Skill Tags (simpler version for candidate sections) ────────────────
def build_skill_tags(skills, bg, fg):
    if not skills:
        return Spacer(1, 1)
    tag_data = []
    row = []
    for i, s in enumerate(skills):
        cell = Table([[Paragraph(
            f"<b>{s}</b>",
            ParagraphStyle("st", fontName="Helvetica-Bold", fontSize=8,
                           textColor=fg, leading=10))]],
            colWidths=[max(len(s)*3.2*mm, 18*mm)])
        cell.setStyle(TableStyle([
            ("BACKGROUND",    (0,0),(-1,-1), bg),
            ("ROWPADDING",    (0,0),(-1,-1), 3),
            ("ROUNDEDCORNERS",[3]),
        ]))
        row.append(cell)
        if len(row) == 6 or i == len(skills) - 1:
            while len(row) < 6:
                row.append(Spacer(1,1))
            tag_data.append(row)
            row = []

    col_w = [170*mm/6] * 6
    t = Table(tag_data, colWidths=col_w)
    t.setStyle(TableStyle([
        ("VALIGN",        (0,0),(-1,-1), "MIDDLE"),
        ("LEFTPADDING",   (0,0),(-1,-1), 2),
        ("RIGHTPADDING",  (0,0),(-1,-1), 2),
        ("TOPPADDING",    (0,0),(-1,-1), 2),
        ("BOTTOMPADDING", (0,0),(-1,-1), 2),
    ]))
    return t


# ── Generate Smart Insights ───────────────────────────────────────────────────
def generate_insights(r, p):

    score = r["final_score"]
    sim = round(r["similarity_score"] * 100, 1)
    pred = round(r["prediction_prob"] * 100, 1)

    poss = r.get("possessed_skills", [])
    miss = r.get("missing_skills", [])

    name = p.get("Name", "The candidate")

    insights = []

    # Status Insight
    if score >= 75:
        insights.append(
            f"✅ {name} is STRONGLY RECOMMENDED for the next recruitment stage. "
            f"The candidate demonstrates high alignment with the job description."
        )

    elif score >= 50:
        insights.append(
            f"⚠️ {name} demonstrates MODERATE suitability for this role. "
            f"Additional technical evaluation is recommended."
        )

    else:
        insights.append(
            f"❌ {name} currently does not meet the expected requirements for this role. "
            f"Skill enhancement is recommended before reconsideration."
        )

    # Similarity Insight
    insights.append(
        f"📊 Resume similarity score achieved: {sim}%, "
        f"with prediction confidence of {pred}%."
    )

    # Skill Analysis
    if len(poss) > len(miss):
        insights.append(
            "✅ Candidate possesses a strong percentage of the required technical skills."
        )
    else:
        insights.append(
            "⚠️ Candidate has multiple skill gaps compared to the expected JD skills."
        )

    # Missing Skills
    if miss:
        insights.append(
            f"❌ Recommended improvement areas: {', '.join(miss[:6])}"
        )

    # Experience Insight
    experience = p.get("Experience", [])
    if experience:
        insights.append(
            "💼 Relevant experience information was identified in the resume."
        )
    else:
        insights.append(
            "⚠️ Limited experience details were detected in the resume."
        )

    # Education Insight
    education = p.get("Education", [])
    if education:
        insights.append(
            "🎓 Educational qualifications were successfully identified."
        )

    return insights


