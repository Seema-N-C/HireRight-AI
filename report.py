# ── Section Header Block ──────────────────────────────────────────────────────
def section_block(title, styles, color=SLATE):
    data = [[Paragraph(f"  {title}", styles["section_header"])]]
    t = Table(data, colWidths=[170*mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,-1), color),
        ("ROWPADDING", (0,0), (-1,-1), 7),
        ("ROUNDEDCORNERS", [4]),
        ("LINEBELOW", (0,0), (-1,-1), 2, PURPLE),
    ]))
    return t


# ── Info Row (label + value pairs) ────────────────────────────────────────────
def info_table(pairs, styles, cols=2):
    """pairs = [("Label", "Value"), ...]"""
    col_w = 170*mm / cols / 2
    rows = []
    for i in range(0, len(pairs), cols):
        row = []
        for j in range(cols):
            if i + j < len(pairs):
                lbl, val = pairs[i+j]
                row += [
                    Paragraph(lbl, styles["field_label"]),
                    Paragraph(str(val) if val else "—", styles["field_value"])
                ]
            else:
                row += [Paragraph("", styles["field_label"]),
                        Paragraph("", styles["field_value"])]
        rows.append(row)

    col_widths = [col_w * 0.55, col_w * 1.45] * cols
    t = Table(rows, colWidths=col_widths)
    t.setStyle(TableStyle([
        ("VALIGN",     (0,0), (-1,-1), "TOP"),
        ("TOPPADDING", (0,0), (-1,-1), 4),
        ("BOTTOMPADDING", (0,0), (-1,-1), 4),
        ("LEFTPADDING",   (0,0), (-1,-1), 4),
        ("RIGHTPADDING",  (0,0), (-1,-1), 4),
    ]))
    return t


# ── Skill Tags Row ────────────────────────────────────────────────────────────
def skill_tags_table(skills, bg_color, text_color, styles, empty_msg="None"):
    if not skills:
        return Paragraph(f"  {empty_msg}", styles["small_gray"])
    # Each skill as a mini table cell
    tags = []
    for s in skills:
        cell = Table([[Paragraph(
            f"<font color='#{text_color.hexval()[2:]}' size='8'><b>{s}</b></font>",
            styles["small_gray"])]],
            colWidths=[len(s)*4.5*mm + 6*mm])
        cell.setStyle(TableStyle([
            ("BACKGROUND",    (0,0), (-1,-1), bg_color),
            ("ROWPADDING",    (0,0), (-1,-1), 3),
            ("ROUNDEDCORNERS",[3]),
        ]))
        tags.append(cell)
    # Wrap in rows of 6
    row_size = 6
    result = []
    for i in range(0, len(tags), row_size):
        chunk = tags[i:i+row_size]
        while len(chunk) < row_size:
            chunk.append(Paragraph("", styles["small_gray"]))
        row_t = Table([chunk], colWidths=[170*mm/row_size]*row_size)
        row_t.setStyle(TableStyle([
            ("VALIGN",  (0,0),(-1,-1),"MIDDLE"),
            ("LEFTPADDING",(0,0),(-1,-1),2),
            ("RIGHTPADDING",(0,0),(-1,-1),2),
            ("TOPPADDING",(0,0),(-1,-1),2),
            ("BOTTOMPADDING",(0,0),(-1,-1),2),
        ]))
        result.append(row_t)
    return result


# ── Score Bar ─────────────────────────────────────────────────────────────────
def score_bar_table(label, score, max_score=100, bar_color=PURPLE, styles=None):
    pct = min(score / max_score, 1.0)
    bar_w = 80*mm
    filled = bar_w * pct
    empty  = bar_w - filled

    score_text = f"{score:.1f}%"
    data = [[
        Paragraph(f"<b>{label}</b>", styles["field_label"]),
        Table([[""]], colWidths=[filled if filled > 0 else 0.5]),
        Table([[""]], colWidths=[empty if empty > 0 else 0.5]),
        Paragraph(f"<b>{score_text}</b>", styles["field_value"]),
    ]]
    col_w = [30*mm, filled, empty, 18*mm]
    t = Table(data, colWidths=col_w)
    t.setStyle(TableStyle([
        ("BACKGROUND",    (1,0),(1,0), bar_color),
        ("BACKGROUND",    (2,0),(2,0), MID_GRAY),
        ("ROWPADDING",    (0,0),(-1,-1), 3),
        ("VALIGN",        (0,0),(-1,-1), "MIDDLE"),
        ("ROUNDEDCORNERS",[2]),
    ]))
    return t


