# ── CSV Export ────────────────────────────────────────────────────────────────
def build_csv(final_results) -> bytes:
    output = io.StringIO()
    fieldnames = [
        "Rank", "Name", "Email", "Phone", "LinkedIn", "GitHub",
        "Similarity%", "Prediction%", "FinalScore%", "Status",
        "PossessedSkills", "MissingSkills",
        "Education", "Experience", "Projects", "Certifications"
    ]
    writer = csv.DictWriter(output, fieldnames=fieldnames)
    writer.writeheader()

    for rank, r in enumerate(final_results, 1):
        p     = r["parsed"]
        score = r["final_score"]
        if score >= 75:   status = "Shortlisted"
        elif score >= 50: status = "Under Review"
        else:             status = "Rejected"

        def listify(val):
            if isinstance(val, list): return "; ".join(str(v) for v in val)
            return str(val) if val else ""

        writer.writerow({
            "Rank":            rank,
            "Name":            p.get("Name",     ""),
            "Email":           p.get("Email",    ""),
            "Phone":           p.get("Phone",    ""),
            "LinkedIn":        p.get("LinkedIn", ""),
            "GitHub":          p.get("GitHub",   ""),
            "Similarity%":     round(r["similarity_score"] * 100, 2),
            "Prediction%":     round(r["prediction_prob"]  * 100, 2),
            "FinalScore%":     score,
            "Status":          status,
            "PossessedSkills": listify(r.get("possessed_skills", [])),
            "MissingSkills":   listify(r.get("missing_skills",   [])),
            "Education":       listify(p.get("Education",        [])),
            "Experience":      listify(p.get("Experience",       [])),
            "Projects":        listify(p.get("Projects",         [])),
            "Certifications":  listify(p.get("Certifications",   [])),
        })

    return output.getvalue().encode("utf-8")

