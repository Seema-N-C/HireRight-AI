        canv.setFont("Helvetica", 8)
        canv.drawRightString(w - 15*mm, h - 11*mm,
            f"Recruitment Report  |  {self.report_date}  |  {self.total_candidates} Candidates")

        # Footer bar
        canv.setFillColor(colors.HexColor("#f3f0ff"))
        canv.rect(0, 0, w, 12*mm, fill=1, stroke=0)
        canv.setFillColor(DARK_GRAY)
